import type { MetadataRoute } from "next";
import { getSiteUrl } from "@/lib/seo";

/**
 * Everyone may crawl everything except /api. AI assistant crawlers are listed
 * explicitly so the store stays visible in AI search / answer engines (GEO):
 * their absence from robots is sometimes treated as ambiguous by new bots.
 */
const AI_CRAWLERS = [
  "GPTBot",
  "OAI-SearchBot",
  "ChatGPT-User",
  "ClaudeBot",
  "Claude-Web",
  "anthropic-ai",
  "PerplexityBot",
  "Perplexity-User",
  "Google-Extended",
  "Applebot-Extended",
  "Amazonbot",
  "cohere-ai",
  "CCBot",
];

export default function robots(): MetadataRoute.Robots {
  const base = getSiteUrl();

  return {
    rules: [
      {
        userAgent: "*",
        allow: "/",
        disallow: ["/api/"],
      },
      ...AI_CRAWLERS.map((userAgent) => ({
        userAgent,
        allow: "/",
        disallow: ["/api/"],
      })),
    ],
    sitemap: `${base}/sitemap.xml`,
  };
}
